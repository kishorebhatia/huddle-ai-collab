// Generates web/config.js from environment variables so no project settings live in git.
// Reads real env vars first (Vercel project settings), then falls back to a local .env file.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const env = { ...process.env };
if (existsSync(".env")) {
  for (const line of readFileSync(".env", "utf8").split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !(m[1] in process.env)) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}

const url = env.SUPABASE_URL;
const key = env.SUPABASE_PUBLISHABLE_KEY ?? env.SUPABASE_ANON_KEY;
if (!url || !key) {
  console.error("Missing SUPABASE_URL or SUPABASE_PUBLISHABLE_KEY. Set them in .env (local) or in Vercel project env vars.");
  process.exit(1);
}

writeFileSync(
  "web/config.js",
  `// Generated by scripts/write-config.mjs from env vars. Do not edit or commit.\n` +
    `export const SUPABASE_URL = ${JSON.stringify(url)};\n` +
    `export const SUPABASE_KEY = ${JSON.stringify(key)};\n`,
);
console.log(`wrote web/config.js for ${url}`);
